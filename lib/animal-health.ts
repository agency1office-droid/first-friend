const NOT_EVIDENCE = /음성|예방|백신|접종|구충|검사예정|이상없|(?<!비)정상|완치|치료완료|치료됨|사상충약|엄마|어미|모견|모묘|임신|흔적|아물|아문|나았|나은|부상없|외상없|상처없/;

export function classifyHealth(memo: string | null | undefined): HealthState {
  const clauses = (memo || "").split(/[,;/\n·!?.]/).map(clause => clause.replace(/\s+/g, ""));
  return clauses.some(clause => CARE_TERMS.test(clause) && !NOT_EVIDENCE.test(clause)) ? "care" : "ok";
}
