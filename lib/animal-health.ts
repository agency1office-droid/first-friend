// "완치"는 그 절의 병만 풀어 주므로 다른 절의 표현은 그대로 남습니다.
const NOT_EVIDENCE = /음성|예방|백신|접종|구충|검사예정|이상없|(?<!비)정상|완치|치료완료|치료됨|사상충약|엄마|어미|모견|모묘|임신|흔적|아물|아문|나았|나은|부상없|외상없|상처없/;

/** 메모에서 치료·관리 근거가 된 표현들(중복 제거). 비어 있으면 양호·미확인입니다. */
export function healthEvidence(memo: string | null | undefined): string[] {
  const clauses = (memo || "").split(/[,;/\n·!?.]/).map(clause => clause.replace(/\s+/g, ""));
  return [...new Set(clauses.filter(clause => !NOT_EVIDENCE.test(clause)).flatMap(clause => clause.match(new RegExp(CARE_TERMS, "g")) || []))];
}

export function classifyHealth(memo: string | null | undefined): HealthState {
  return healthEvidence(memo).length ? "care" : "ok";
}
